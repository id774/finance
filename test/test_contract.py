def test_regenerated_indicators_match_the_committed_fixture(raw_prices, indicator_fixture):
    """ Every computed column of ti_N225.csv reproduces from stock_N225.csv. """
    computed = build_indicator_frame(raw_prices).stock

    checked = 0
    for column in indicator_fixture.columns:
        if column in PRICE_COLUMNS or column in ("classified", "predicted"):
            continue
        assert column in computed.columns, "lost column {0}".format(column)

        expected = indicator_fixture[column].astype("float64")
        actual = computed[column].reindex(indicator_fixture.index).astype("float64")

        # The pattern of leading NaNs is part of the contract: it is how
        # long each indicator takes to warm up, and the dashboard renders
        # those cells empty.
        assert (expected.isna() == actual.isna()).all(), "NaN pattern moved in {0}".format(column)

        both = expected.notna()
        np.testing.assert_allclose(
            actual[both].to_numpy(),
            expected[both].to_numpy(),
            rtol=1e-12,
            atol=0,
            err_msg="values moved in {0}".format(column),
        )
        checked += 1

    assert checked == 42, "expected 42 computed columns, checked {0}".format(checked)


