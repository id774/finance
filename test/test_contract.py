# test_contract.py: The data contract with finance-dashboard
#
#  Description:
#  Pin the format of every file this repository generates, in the terms
#  the consumer reads them in.
#
#  finance-dashboard holds no copy of this repository's code. The two
#  are joined by a directory of files, and the joint is only as good as
#  these assertions. Two properties of the consumer make that sharper
#  than it sounds:
#
#  - Summary files are parsed positionally. finance_dashboard/data.py
#    skips the header line, splits on tab and zips the fields against a
#    fixed list of names. A column inserted, removed or reordered here
#    does not fail there; it silently shifts every later value into the
#    wrong name. The parser below is written the same way on purpose.
#  - ti_CODE.csv is parsed by header name through csv.DictReader, with
#    each name lowercased and non-alphanumerics collapsed to
#    underscores. Renaming a column breaks it; reordering does not.
#
#  The indicator file is checked against test/ti_N225.csv, which was
#  generated by the implementation this one replaces. Regenerating its
#  computed indicator columns and finding them equal is what shows the
#  contract survived the rewrite.
#
#  Test Cases:
#  - Regenerated indicator columns match the committed fixture.
#  - ti_CODE.csv keeps its name, separator, index label, column order
#    and header spelling, and normalizes to the keys the dashboard reads.
#  - classified and predicted appear on the last row only.
#  - stock_CODE.csv keeps its six columns in canonical order.
#  - The ten and nine column summary layouts parse positionally into the
#    dashboard's own column lists.
#  - stocks.txt parses as code and name.
#  - data_source.txt states the source and the last trading day, and an
#    unknown last trading day is left empty rather than filled with
#    today.
#  - History files carry the dated double extension.
#  - Chart file names follow the window length rule.
#
