def normalize_header(name: str) -> str:
    """ Normalize a header cell exactly as finance_dashboard/data.py does. """
    return re.sub(r"[^0-9a-z]+", "_", (name or "").strip().lower()).strip("_")


def read_summary_as_dashboard(path, columns) -> list[dict[str, str]]:
    """ Parse a summary file the way finance_dashboard/data.py parses it. """
    rows: list[dict[str, str]] = []
    with open(path, encoding="utf-8", errors="replace") as handle:
        for line in handle:
            fields = line.rstrip("\n").split("\t")
            if not fields or not fields[0] or fields[0] == "Code":
                continue
            row = dict(zip(columns, fields, strict=False))
            for column in columns:
                row.setdefault(column, "")
            rows.append(row)
    return rows


def read_indicators_as_dashboard(path) -> list[dict[str, str]]:
    """ Parse an indicator file the way finance_dashboard/data.py parses it. """
    rows: list[dict[str, str]] = []
    with open(path, encoding="utf-8", errors="replace", newline="") as handle:
        for record in csv.DictReader(handle):
            row = {
                normalize_header(key): (value or "")
                for key, value in record.items()
                if key
            }
            if not row.get("date") or row.get("date") == "Date":
                continue
            rows.append(row)
    return rows


