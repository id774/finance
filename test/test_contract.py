def build_frames(indicator_fixture: pd.DataFrame, today: date) -> dict:
    """ Build two indicator frames dated so that they count as current. """
    frame = indicator_fixture.copy()
    frame.loc[frame.index[-1], "classified"] = 1
    frame.loc[frame.index[-1], "predicted"] = 19125
    shifted = frame.copy()
    shifted.index = pd.date_range(end=pd.Timestamp(today), periods=len(frame), freq="B")
    other = shifted.copy()
    other["Adj Close"] = other["Adj Close"] * 0.5
    return {("7203", "トヨタ"): shifted, ("6758", "ソニー"): other}


def test_portfolio_layout_parses_positionally(settings, indicator_fixture, today):
    frames = build_frames(indicator_fixture, today)
    table = Aggregator(frames).summarize(span=1, sortkey="Ratio", as_of=today)
    path = settings.data_file("portfolio.csv")
    storage.write_summary_csv(table, path)

    header = path.read_text(encoding="utf-8").splitlines()[0]
    assert header.split("\t") == [
        "Code",
        "Open",
        "High",
        "Low",
        "Close",
        "Change",
        "Ratio",
        "Trend",
        "Pred",
        "Name",
    ]

    rows = read_summary_as_dashboard(path, DASHBOARD_PORTFOLIO_COLUMNS)
    assert len(rows) == 2
    for row in rows:
        assert row["code"] in {"7203", "6758"}
        assert row["name"] in {"トヨタ", "ソニー"}
        # A shifted column would put a name where a number belongs.
        for numeric in ("open", "high", "low", "close", "diff", "ratio", "predict"):
            float(row[numeric])
        assert row["trend"] in {"0", "1"}


